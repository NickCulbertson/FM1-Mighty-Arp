#!/usr/bin/env python3
"""Write the host test that plays every sound in app/app.c's PRESET list once (tests/run_tests.sh runs it): each
sounds, stays finite, and leaves a WAV (app/build/host/snd_NN.wav) for checking levels by ear or by number."""
import re
from pathlib import Path

src = (Path(__file__).resolve().parents[1] / "app/app.c").read_text()
table = src[src.index("static const preset_t PRESET[] = {"):src.index("#define NPRESET")]
names = re.findall(r'^\s*\{"([^"]+)",', table, re.M)
order = [int(v) for v in re.findall(r"\d+", src[src.index("static const uint8_t ORDER[] = {"):].split("};")[0][30:])]
assert sorted(order) == list(range(len(names))), "ORDER: every sound once"
print("# Every sound plays and sounds: generated by tests/make_sounds_test.py from app.c's PRESET list")
print("wait 600")
print("expect play_keys 0")              # KEYS (PLAY would pass through SEQ)
print("wait 30")
print(f"expect npreset {len(names)}")
for i in order:                         # PRESET goes through them in ORDER
    n = names[i]
    print(f"# {n}")
    print(f"expect preset {i}")
    print("peakreset")
    print(f"wav snd_{i:02d}.wav")
    print("key 7 down 100")
    print("wait 900")
    print("key 7 up")
    print("wait 600")
    print("wavstop")
    print("expect peak_db_min -36")
    print("expect dsp_resets 0")
    print("spin PRESET 1")
    print("wait 300")
